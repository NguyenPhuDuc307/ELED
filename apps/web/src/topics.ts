const english = (name: string) => name.replaceAll("_", " ");
/** "Animals - Pets" → ["Động vật", "Thú cưng"] (hoặc tiếng Anh khi `vi` là false). */
export function topicLabel(topic: string, vi: boolean): [string, string] {
  // Tên tệp trên macOS có thể ở dạng NFD ("décor" tách dấu).
  const [group, ...rest] = topic.normalize("NFC").split(" - ");
  const name = rest.join(" - ");
  return vi ? [groups[group] ?? english(group), topics[name] ?? english(name)] : [english(group), english(name)];
}
/** Tên nhóm chủ đề (thư mục) như "Food_and_drink". */
export function topicGroupLabel(group: string, vi: boolean) {
  return vi ? groups[group] ?? english(group) : english(group);
}
